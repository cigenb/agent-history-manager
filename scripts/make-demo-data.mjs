const BASE = Date.parse('2026-10-21T01:30:00Z')
const iso = (minutes) => new Date(BASE + minutes * 60_000).toISOString()
const uuidFrom = (seed) => {
  const h = createHash('sha1').update(seed).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`
}
const folderOf = (path) => path.replace(/[^a-zA-Z0-9]/g, '-')
const write = async (path, content) => {
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, content)
}

/** Writes records in the session file format: one JSON object per line, one content block per assistant record. */
class Transcript {
  constructor(seed, cwd, { sidechain = false, agentId } = {}) {
    this.seed = seed
    this.cwd = cwd
    this.sidechain = sidechain
    this.agentId = agentId
    this.records = []
    this.n = 0
    this.minute = 0
  }
  id(kind) {
    return uuidFrom(`${this.seed}:${kind}:${this.n++}`)
  }
  base(extra) {
    return {
      uuid: this.id('uuid'),
      timestamp: iso(this.minute),
      cwd: this.cwd,
      isSidechain: this.sidechain,
      ...(this.agentId ? { agentId: this.agentId } : {}),
      ...extra,
    }
  }
  at(minute) {
    this.minute = minute
    return this
  }
  prompt(text) {
    const origin = this.sidechain ? {} : { origin: { kind: 'human' }, entrypoint: 'cli' }
    this.records.push(this.base({ type: 'user', ...origin, message: { role: 'user', content: text } }))
    this.minute += 1
  }
  say(text, end = false) {
    this.records.push(
      this.base({
        type: 'assistant',
        message: { id: `msg_${this.id('msg')}`, role: 'assistant', content: [{ type: 'text', text }], stop_reason: end ? 'end_turn' : 'tool_use' },
      }),
    )
    this.minute += 1
  }
  tool(name, input, result) {
    const id = `toolu_${this.id('tool').replace(/-/g, '').slice(0, 24)}`
    this.records.push(
      this.base({
        type: 'assistant',
        message: { id: `msg_${this.id('msg')}`, role: 'assistant', content: [{ type: 'tool_use', id, name, input }], stop_reason: 'tool_use' },
      }),
    )
    if (result !== undefined) {
      this.records.push(this.base({ type: 'user', message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: id, content: result }] } }))
    }
    return id
  }
  /** A message Claude Code delivers to the parent session when a background subagent reports back. */
  agentReport(agentId, toolUseId, report) {
    this.records.push(
      this.base({ type: 'user', isMeta: true, origin: { kind: 'peer', from: agentId, name: 'general-purpose' }, message: { role: 'user', content: report } }),
    )
    this.records.push(
      this.base({
        type: 'user',
        isMeta: true,
        origin: { kind: 'task-notification' },
        message: { role: 'user', content: `<task-notification>\n<task-id>${agentId}</task-id>\n<tool-use-id>${toolUseId}</tool-use-id>\n<status>completed</status>\n</task-notification>` },
      }),
    )
  }
  title(text) {
    this.records.push({ type: 'custom-title', customTitle: text, sessionId: this.seed })
  }
  text() {
    return this.records.map((r) => JSON.stringify(r)).join('\n') + '\n'
  }
}

const projects = []

async function project(name) {
  const cwd = join(workDir, name)
  await mkdir(cwd, { recursive: true })
  const p = { name, cwd, dir: join(projectsDir, folderOf(cwd)), key: cwd.toLowerCase() }
  projects.push(p)
  return p
}

async function session(p, name, build) {
  const id = uuidFrom(`session:${p.name}:${name}`)
  const t = new Transcript(id, p.cwd)
  await build(t, id)
  await write(join(p.dir, `${id}.jsonl`), t.text())
  return id
}

